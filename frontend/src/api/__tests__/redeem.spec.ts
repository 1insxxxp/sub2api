import { beforeEach, describe, expect, it, vi } from 'vitest'

const { del, get, post } = vi.hoisted(() => ({
  del: vi.fn(),
  get: vi.fn(),
  post: vi.fn()
}))

vi.mock('@/api/client', () => ({
  apiClient: {
    delete: del,
    get,
    post
  }
}))

import {
  deleteGeneratedBatch,
  deleteGenerated,
  generateBalanceTransferCode,
  generateBalanceTransferCodes,
  generateUserBalanceTransferCodes,
  getGenerated,
  getHistory,
  type GenerateBalanceTransferCodeRequest,
  type GeneratedRedeemCode,
  type RedeemHistoryItem
} from '@/api/redeem'
import type { PaginatedResponse } from '@/types'

describe('redeem api balance transfer codes', () => {
  beforeEach(() => {
    del.mockReset()
    get.mockReset()
    post.mockReset()
  })

  it('posts the current user balance transfer redeem code payload and returns the first code', async () => {
    const request: GenerateBalanceTransferCodeRequest = {
      amount: 12.5,
      expires_in_days: 14,
      notes: 'for teammate',
      count: 1
    }
    const response: GeneratedRedeemCode = {
      id: 18,
      code: 'ABCD-EFGH',
      type: 'balance',
      value: 12.5,
      status: 'unused',
      used_by: null,
      used_at: null,
      created_at: '2026-08-20T12:00:00Z',
      expires_at: '2026-09-03T12:00:00Z',
      created_by: 7,
      source: 'user_balance_transfer'
    }
    post.mockResolvedValue({ data: response })

    const result = await generateBalanceTransferCode(request)

    expect(post).toHaveBeenCalledWith('/admin/workbench/redeem/generated', request)
    expect(result).toEqual(response)
  })

  it('posts batch balance transfer redeem code payload', async () => {
    const request: GenerateBalanceTransferCodeRequest = {
      amount: 5,
      count: 3,
      expires_in_days: 14,
      notes: 'team drop',
      single_use_per_user: true
    }
    const response: GeneratedRedeemCode[] = [
      {
        id: 18,
        code: 'A',
        type: 'balance',
        value: 5,
        status: 'unused',
        used_by: null,
        used_at: null,
        created_at: '2026-08-20T12:00:00Z',
        created_by: 7,
        source: 'user_balance_transfer',
        single_use_per_user: true
      }
    ]
    post.mockResolvedValue({ data: response })

    const result = await generateBalanceTransferCodes(request)

    expect(post).toHaveBeenCalledWith('/admin/workbench/redeem/generated', request)
    expect(result).toEqual(response)
  })

  it('keeps the explicitly enabled user balance transfer endpoint separate', async () => {
    const request: GenerateBalanceTransferCodeRequest = { amount: 5, count: 1 }
    const response: GeneratedRedeemCode[] = [
      {
        id: 19,
        code: 'USER-CODE',
        type: 'balance',
        value: 5,
        status: 'unused',
        used_by: null,
        used_at: null,
        created_at: '2026-08-30T12:00:00Z',
        expires_at: '2026-09-29T12:00:00Z',
        created_by: 8,
        source: 'user_balance_transfer'
      }
    ]
    post.mockResolvedValue({ data: response })

    await expect(generateUserBalanceTransferCodes(request)).resolves.toEqual(response)
    expect(post).toHaveBeenCalledWith('/redeem/generate', request)
  })

  it('loads paginated redeem history for the current user', async () => {
    const item: RedeemHistoryItem = {
      id: 18,
      code: 'HISTORY',
      type: 'balance',
      value: 12.5,
      status: 'used',
      used_at: '2026-08-20T12:00:00Z',
      created_at: '2026-08-20T12:00:00Z'
    }
    const response: PaginatedResponse<RedeemHistoryItem> = {
      items: [item],
      total: 21,
      page: 2,
      page_size: 10,
      pages: 3
    }
    get.mockResolvedValue({ data: response })

    const result = await getHistory({ page: 2, page_size: 10 })

    expect(get).toHaveBeenCalledWith('/redeem/history', { params: { page: 2, page_size: 10 } })
    expect(result).toEqual(response)
  })

  it('loads paginated redeem codes generated by the current user', async () => {
    const item: GeneratedRedeemCode = {
      id: 18,
      code: 'ABCD-EFGH',
      type: 'balance',
      value: 12.5,
      status: 'unused',
      used_by: null,
      used_at: null,
      created_at: '2026-08-20T12:00:00Z',
      created_by: 7,
      source: 'user_balance_transfer'
    }
    const response: PaginatedResponse<GeneratedRedeemCode> = {
      items: [item],
      total: 11,
      page: 1,
      page_size: 10,
      pages: 2
    }
    get.mockResolvedValue({ data: response })

    const result = await getGenerated({ page: 1, page_size: 10 })

    expect(get).toHaveBeenCalledWith('/admin/workbench/redeem/generated', { params: { page: 1, page_size: 10 } })
    expect(result).toEqual(response)
  })

  it('deletes a generated balance transfer redeem code', async () => {
    const response: GeneratedRedeemCode = {
      id: 18,
      code: 'ABCD-EFGH',
      type: 'balance',
      value: 12.5,
      status: 'unused',
      used_by: null,
      used_at: null,
      created_at: '2026-08-20T12:00:00Z',
      created_by: 7,
      source: 'user_balance_transfer'
    }
    del.mockResolvedValue({ data: response })

    const result = await deleteGenerated(18)

    expect(del).toHaveBeenCalledWith('/admin/workbench/redeem/generated/18')
    expect(result).toEqual(response)
  })

  it('batch deletes generated balance transfer redeem codes', async () => {
    const response: GeneratedRedeemCode[] = [
      {
        id: 18,
        code: 'ABCD-EFGH',
        type: 'balance',
        value: 12.5,
        status: 'unused',
        used_by: null,
        used_at: null,
        created_at: '2026-08-20T12:00:00Z',
        created_by: 7,
        source: 'user_balance_transfer'
      },
      {
        id: 19,
        code: 'IJKL-MNOP',
        type: 'balance',
        value: 5,
        status: 'unused',
        used_by: null,
        used_at: null,
        created_at: '2026-08-20T12:00:00Z',
        created_by: 7,
        source: 'user_balance_transfer'
      }
    ]
    post.mockResolvedValue({ data: response })

    const result = await deleteGeneratedBatch([18, 19])

    expect(post).toHaveBeenCalledWith('/admin/workbench/redeem/generated/batch-delete', { ids: [18, 19] })
    expect(result).toEqual(response)
  })
})
